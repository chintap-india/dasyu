import { describe, it, expect } from 'vitest';
import path from 'node:path';
import { loadPlugin } from '../src/plugins/loader';
import { analyzeReadability } from '../examples/plugins/readability-grade.mjs';
import { lintProse } from '../examples/plugins/prose-lint.mjs';

describe('Public Example Plugins', () => {
  const readabilityPath = path.resolve(__dirname, '../examples/plugins/readability-grade.mjs');
  const proseLintPath = path.resolve(__dirname, '../examples/plugins/prose-lint.mjs');

  describe('Readability & Grade Level Plugin', () => {
    it('should be dynamically loadable by Dasyu plugin loader', async () => {
      const plugin = await loadPlugin(readabilityPath);
      expect(plugin.name).toBe('readability-grade');
      expect(typeof plugin.onExtract).toBe('function');
      expect(typeof plugin.onAnalyze).toBe('function');
    });

    it('should calculate accurate readability metrics for simple English', () => {
      const simpleText = 'The cat sat on the mat. The dog saw the cat. They ran in the sun.';
      const res = analyzeReadability(simpleText);
      expect(res.fleschReadingEase).toBeGreaterThan(80);
      expect(res.fleschKincaidGrade).toBeLessThan(5);
      expect(res.targetAge).toMatch(/years/i);
    });

    it('should calculate higher grade levels for complex technical prose', () => {
      const complexText =
        'The algorithmic complexity manifests significant computational degradation due to recursive multidimensional tensor factorization.';
      const res = analyzeReadability(complexText);
      expect(res.fleschReadingEase).toBeLessThan(40);
      expect(res.fleschKincaidGrade).toBeGreaterThan(12);
    });

    it('should execute onExtract and onAnalyze lifecycle hooks', async () => {
      const plugin = await loadPlugin(readabilityPath);
      const ctx: any = {
        data: {
          metadata: {
            markdown: 'Simple documentation for users. Easy to read and understand.',
          },
        },
      };

      await plugin.onExtract!(ctx, '/path/to/content.md');
      expect(ctx.data.metadata.readability).toBeDefined();

      const analysis = await plugin.onAnalyze!(ctx);
      expect(analysis).toHaveProperty('readabilityScore');
      expect(analysis).toHaveProperty('readingGrade');
      expect(analysis).toHaveProperty('targetAudience');
    });
  });

  describe('Prose & Grammar Linter Plugin', () => {
    it('should be dynamically loadable by Dasyu plugin loader', async () => {
      const plugin = await loadPlugin(proseLintPath);
      expect(plugin.name).toBe('prose-lint');
      expect(typeof plugin.onExtract).toBe('function');
      expect(typeof plugin.onAnalyze).toBe('function');
    });

    it('should detect passive voice, weasel words, and complex jargon', () => {
      const badText =
        'The database was terminated by the administrator. It is very obviously required to utilize simpler tools.';
      const res = lintProse(badText);

      expect(res.stats.passiveVoiceCount).toBeGreaterThanOrEqual(1);
      expect(res.stats.weaselWordCount).toBeGreaterThanOrEqual(1);
      expect(res.stats.complexWordCount).toBeGreaterThanOrEqual(1);
      expect(res.qualityScore).toBeLessThan(100);
      expect(res.suggestions.length).toBeGreaterThan(0);
    });

    it('should give 100% score to clean active voice prose', () => {
      const cleanText = 'We deploy code daily. Fast tests catch bugs early.';
      const res = lintProse(cleanText);
      expect(res.qualityScore).toBe(100);
      expect(res.suggestions).toHaveLength(0);
    });

    it('should execute onExtract and onAnalyze lifecycle hooks', async () => {
      const plugin = await loadPlugin(proseLintPath);
      const ctx: any = {
        data: {
          metadata: {
            markdown: 'This report was generated by Dasyu. It is extremely fast.',
          },
        },
      };

      await plugin.onExtract!(ctx, '/path/to/content.md');
      expect(ctx.data.metadata.proseLint).toBeDefined();

      const analysis = await plugin.onAnalyze!(ctx);
      expect(analysis).toHaveProperty('proseQualityScore');
      expect(analysis).toHaveProperty('proseIssues');
    });
  });
});
